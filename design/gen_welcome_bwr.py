#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成 B 屏(FPC2 三色 400x300 BWR)欢迎页，直接输出两张 1bpp 平面数组。

为什么不像 A 屏那样烘焙 PNG：
  B 屏走 Uc1679Display(SSD1683) 驱动，接口只吃 bw/red 两张平面
  （bw: 1=白 0=黑；red: 1=红 0=非红），没有 LVGL 解码通道。所以这里在
  生成阶段就把版式直接栅格化成平面数组，固件 include 即可送显，零解码、
  零网络依赖 —— 未联网 / 未绑定 / 后台没配内容时都能显示。

与 A 屏分工：
  A 屏 = 信息引导（当前卡在哪步、下一步做什么，见 gen_guide.py）
  B 屏 = 品牌欢迎页（本文件）

三色版面约束：
  - 只用纯黑/纯白/纯红三色平涂，不做灰度与抖动（三色屏没有中间色）
  - 红色只用在「售后群」药丸上：红底白字，是全屏唯一的彩色锚点
  - 药丸内的白字靠 bw=1 且 red=0 实现，红色底靠 red=1 实现

输出：
  firmware/.../welcome_bwr.h        (welcome_bwr_bw / welcome_bwr_red 数组)
  design/b_screen_welcome_preview.png  (RGB 预览，模拟三色观感)
"""
import os
from PIL import Image, ImageDraw, ImageFont

W, H = 400, 300
STRIDE = (W + 7) // 8          # 50
FONT_DIR = "/c/Windows/Fonts"
SIMHEI = os.path.join(FONT_DIR, "simhei.ttf")
MSYH = os.path.join(FONT_DIR, "msyh.ttc")
LOGO_SRC = r"E:\electron\screen\inksight-main\inksight-main\小悟logo.png"

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FW_DIR = os.path.join(BASE, "firmware", "s3", "main", "boards", "custom",
                      "ssd2683za-s3-epd42")
OUT_H = os.path.join(FW_DIR, "welcome_bwr.h")
OUT_PRE = os.path.join(BASE, "design", "b_screen_welcome_preview.png")

WHITE = (255, 255, 255)
BLACK = (0, 0, 0)
RED = (220, 30, 40)

THRESH = 160


def load_logo(target_w=186):
    """读小悟 logo（白底黑+金），取墨色紧致包围盒后阈值化为纯黑白。"""
    im = Image.open(LOGO_SRC).convert("L")
    px = im.load()
    W0, H0 = im.size
    minx, miny, maxx, maxy = W0, H0, -1, -1
    for y in range(0, H0, 2):
        for x in range(0, W0, 2):
            if px[x, y] < 128:
                minx = min(minx, x); maxx = max(maxx, x)
                miny = min(miny, y); maxy = max(maxy, y)
    if maxx >= 0:
        pad = 6
        minx = max(0, minx - pad); miny = max(0, miny - pad)
        maxx = min(W0 - 1, maxx + pad); maxy = min(H0 - 1, maxy + pad)
        im = im.crop((minx, miny, maxx + 1, maxy + 1))
    im = im.point(lambda p: 0 if p < THRESH else 255)
    w, h = im.size
    scale = target_w / w
    return im.resize((max(1, round(w * scale)), max(1, round(h * scale))),
                     Image.LANCZOS)


def draw_corner_ticks(d, inset=10, t=2, L=16):
    pts = [
        (inset, inset, 1, 1), (W - inset, inset, -1, 1),
        (inset, H - inset, 1, -1), (W - inset, H - inset, -1, -1),
    ]
    for cx, cy, dx, dy in pts:
        d.line([(cx, cy), (cx + dx * L, cy)], fill=BLACK, width=t)
        d.line([(cx, cy), (cx, cy + dy * L)], fill=BLACK, width=t)


def render():
    """按三色平涂规则画 400x300 RGB 图。"""
    canvas = Image.new("RGB", (W, H), WHITE)
    d = ImageDraw.Draw(canvas)

    draw_corner_ticks(d)

    logo = load_logo(186).convert("RGB")
    canvas.paste(logo, ((W - logo.width) // 2, 14))

    title_font = ImageFont.truetype(SIMHEI, 26)
    d.text((W // 2, 168), "欢迎加入小悟AI智研社", font=title_font,
           fill=BLACK, anchor="mm")

    # 红色焦点药丸（红底白字）
    pill_text = "售后技术QQ群：65558220"
    pill_font = ImageFont.truetype(SIMHEI, 15)
    tb = d.textbbox((0, 0), pill_text, font=pill_font)
    tw, th = tb[2] - tb[0], tb[3] - tb[1]
    pad_x, pad_y = 18, 9
    pill_w, pill_h = tw + pad_x * 2, th + pad_y * 2
    pill_x = (W - pill_w) // 2
    pill_y = 204
    d.rounded_rectangle([pill_x, pill_y, pill_x + pill_w, pill_y + pill_h],
                        radius=min(12, pill_h // 2), fill=RED)
    d.text((W // 2, pill_y + pill_h // 2), pill_text, font=pill_font,
           fill=WHITE, anchor="mm")

    hint_font = ImageFont.truetype(MSYH, 12)
    d.text((W // 2, 284), "dualcn.xiaowuai.vip · 后台配置屏幕内容",
           font=hint_font, fill=BLACK, anchor="mm")
    return canvas


def to_planes(canvas):
    """RGB → (bw, red) 两张 1bpp 平面。bw: 1=白 0=黑；red: 1=红。"""
    bw = bytearray(STRIDE * H)
    red = bytearray(STRIDE * H)
    px = canvas.load()
    for y in range(H):
        for x in range(W):
            r, g, b = px[x, y]
            is_red = r > 120 and g < 110 and b < 110
            is_black = (r < 110 and g < 110 and b < 110)
            bit = 0x80 >> (x & 7)
            idx = y * STRIDE + (x >> 3)
            if is_red:
                bw[idx] |= bit      # 红色像素的底色按白处理，由 red 平面决定
                red[idx] |= bit
            elif is_black:
                bw[idx] &= ~bit & 0xFF
            else:
                bw[idx] |= bit      # 白
    return bw, red


def emit_header(bw, red):
    with open(OUT_H, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by design/gen_welcome_bwr.py. DO NOT EDIT.\n")
        f.write("// B 屏(FPC2 三色 400x300)内置欢迎页：两张 1bpp 平面。\n")
        f.write("// bw : 1=白 0=黑  red: 1=红 0=非红（与 Uc1679Display 约定一致）\n")
        f.write("#pragma once\n#include <cstddef>\n#include <stdint.h>\n\n")
        f.write("static const int kWelcomeBwrWidth = %d;\n" % W)
        f.write("static const int kWelcomeBwrHeight = %d;\n" % H)
        f.write("static const size_t kWelcomeBwrPlaneBytes = %d;\n\n" % len(bw))
        for name, data in (("welcome_bwr_bw", bw), ("welcome_bwr_red", red)):
            f.write("static const uint8_t %s[] = {\n" % name)
            for i in range(0, len(data), 16):
                chunk = data[i:i + 16]
                f.write("  " + ",".join("0x%02x" % b for b in chunk) + ",\n")
            f.write("};\n\n")


def main():
    canvas = render()
    canvas.save(OUT_PRE)
    bw, red = to_planes(canvas)
    emit_header(bw, red)
    print("saved:", OUT_H, "planes", len(bw), "bytes each | preview", OUT_PRE)


if __name__ == "__main__":
    main()
